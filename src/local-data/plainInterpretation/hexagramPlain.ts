function build(): Record<number, PlainHexagram> {
  const map: Record<number, PlainHexagram> = {}
  for (const [kingWen, name, simple, action] of RAW) {
    map[kingWen] = { kingWen, name, classic: name, simple, action }
  }
  return map
}

/** 只读冻结，避免 Vue 深响应开销 */
export const PLAIN_HEXAGRAMS: Record<number, PlainHexagram> = Object.freeze(build())

/** 同步取某卦的普通用户解释，未收录返回 undefined */
export function getPlainHexagram(kingWen: number): PlainHexagram | undefined {
  return PLAIN_HEXAGRAMS[kingWen]
}

/** 长辈友好一句话：优先显式 elder，缺省回退 simple */
export function getElderPlain(kingWen: number): string | undefined {
  const p = PLAIN_HEXAGRAMS[kingWen]
  return p ? (p.elder ?? p.simple) : undefined
}
